function toTraditional(value: string): string {
  let result = value
  for (const [from, to] of Object.entries(traditionalPhrases)) result = result.replaceAll(from, to)
  return [...result].map((char) => traditionalChars[char] ?? char).join('')
}

let activeLocale: UiLocale = 'en'

export function setEmbeddedUiLocale(locale: UiLocale = 'en'): void { activeLocale = locale }
export function getEmbeddedUiLocale(): UiLocale { return activeLocale }

export function translateEmbeddedUi(locale: UiLocale, message: string, values: Record<string, string | number> = {}): string {
  const metadata = translateSystemMetadata(locale, message)
  const simplified = embeddedUiZhCN[message]
  const result = locale === 'en' ? message : metadata !== message ? metadata : simplified
    ? locale === 'zh-TW' ? toTraditional(simplified) : simplified : message
  return result.replace(/\{\{(\w+)\}\}/g, (placeholder, key: string) =>
    values[key] === undefined ? placeholder : String(values[key]))
}

export function embeddedT(message: string, values: Record<string, string | number> = {}): string {
  return translateEmbeddedUi(activeLocale, message, values)
}
